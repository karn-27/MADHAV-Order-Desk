import assert from 'node:assert/strict';
import {products,sampleParse,commitOrder,reservationReview,updateReservation,replyFor,available,recordPayment} from '../lib/domain.ts';
const original=sampleParse('Kal 1 chocolate cake book karna hai','2026-10-17');
const saved=commitOrder(original,products,[],'Aanya','message-a');
const changed={...original,productId:'vanilla'};
const review=reservationReview(changed,products,saved,'message-a');
assert.equal(review.changed,true);
assert.equal(saved[0].productId,'chocolate','editing a proposal must not mutate the stored reservation');
assert.equal(replyFor(changed,products,saved,saved[0]).includes('reserve ho gaya'),false,'unsaved change must not claim reservation');
const updated=updateReservation(changed,products,saved,'message-a');
assert.equal(updated.length,1);assert.equal(updated[0].id,saved[0].id);assert.equal(updated[0].productId,'vanilla');assert.equal(updated[0].total,750);
assert.equal(available(products[0],original.date!,updated),4,'old item capacity is released');
assert.equal(available(products[1],original.date!,updated),2,'new item capacity is reserved');
assert.equal(reservationReview(changed,products,updated,'message-a').changed,false);
assert.match(replyFor(changed,products,updated,updated[0]),/reserve ho gaya/);
assert.doesNotMatch(replyFor(original,products,[]),/owner approval/i);
assert.doesNotMatch(replyFor({...original,language:'en'},products,[]),/owner approval/i);
assert.throws(()=>updateReservation({...changed,productId:'redvelvet'},products,saved,'message-a'),/capacity/);
assert.equal(saved[0].productId,'chocolate','failed update preserves original');
const full=commitOrder({...original,quantity:4},products,[],'Aanya','full');
assert.equal(reservationReview({...original,quantity:4},products,full,'full').check.errors.length,0,'own reservation does not consume capacity twice');
const paid=[recordPayment(saved[0],850)];
assert.throws(()=>updateReservation(changed,products,paid,'message-a'),/below the payment/);
assert.equal(reservationReview(changed,products,saved,'another-customer-message').order,null,'another message does not inherit reserved status');
const another=commitOrder(changed,products,saved,'Meera','message-b');assert.equal(another.length,2);assert.equal(another[1].customer,'Meera');assert.equal(another[0].customer,'Aanya');
const newDate={...original,date:'2026-10-19'};assert.equal(reservationReview(newDate,products,saved,'message-a').changed,true);
const moved=updateReservation(newDate,products,saved,'message-a');assert.equal(available(products[0],original.date!,moved),4);
assert.equal(updateReservation(original,products,saved,'message-a'),saved,'unchanged approval is idempotent');
console.log('Reservation-edit regression passed: unsaved changes, approval, stock transfer, duplicate prevention, payment guard and customer isolation.');

import assert from 'node:assert/strict';
import {products,sampleParse,alternativesFor,replyFor,commitOrder,updateReservation} from '../lib/domain.ts';
const p=sampleParse('Kal 1 red velvet cake chahiye','2026-10-17');
const choices=alternativesFor(p,products,[]);
assert.deepEqual(choices.map(x=>x.id),['chocolate','vanilla']);
const reply=replyFor(p,products,[]);
assert.match(reply,/Chocolate Truffle.*₹900/);
assert.match(reply,/Vanilla Cloud.*₹750/);
assert.match(reply,/Kaunsa pasand/);
assert.doesNotMatch(reply,/reserve ho gaya/);
assert.equal(p.productId,'redvelvet','suggestion must not substitute the requested item');
assert.throws(()=>commitOrder(p,products,[],'Rohan','rohan'),/capacity/);
const full=commitOrder({...p,productId:'chocolate',quantity:4},products,[],'Aanya','aanya');
assert.deepEqual(alternativesFor(p,products,full).map(x=>x.id),['vanilla'],'sold-out alternative excluded');
assert.equal(alternativesFor({...p,quantity:4},products,full).length,0,'enough for entire quantity required');
assert.match(replyFor({...p,quantity:4,language:'en'},products,full),/another pickup date/);
assert.deepEqual(alternativesFor({...p,date:'2026-10-19'},products,full).map(x=>x.id),['chocolate','vanilla'],'stock is per date');
assert.deepEqual(alternativesFor(p,products,full.map(x=>({...x,status:'cancelled'}))).map(x=>x.id),['chocolate','vanilla']);
assert.equal(alternativesFor({...p,date:null},products,[]).length,0);
assert.equal(alternativesFor({...p,intent:'handoff'},products,[]).length,0,'no automatic alternatives for safety-sensitive handoff');
assert.equal(alternativesFor({...p,productId:'chocolate'},products,[]).length,0,'available request does not need replacement');
assert.match(replyFor({...p,quantity:2,language:'en'},products,[]),/₹900 each; 2 total ₹1800/);
const quote={...p,productId:'chocolate'};
assert.match(replyFor(quote,products,[]),/quote:.*₹900; booking advance ₹450/);
const old=commitOrder(quote,products,[],'Aanya','a');
const edited={...quote,productId:'vanilla'};
const next=updateReservation(edited,products,old,'a');
assert.match(replyFor(edited,products,next,next[0],old[0]),/update hua: pehle 1 × Chocolate Truffle.*₹900.*Vanilla Cloud.*₹750.*₹375/);
assert.equal(next.length,1);
assert.match(replyFor({...edited,language:'en'},products,next,next[0],old[0]),/replace that reservation/);
console.log('Alternatives and quote clarity passed: date/quantity capacity, no substitution, sold-out block, grounded pricing and reservation revisions.');

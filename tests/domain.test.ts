import assert from 'node:assert/strict';
import {products,commitOrder,inspect,recordPayment,available,sampleParse,replyFor,businessDate,nextDate} from '../lib/domain.ts';
const p=sampleParse('Kal 1 chocolate cake book karna hai','2026-10-16');
assert.equal(p.quantity,1);assert.equal(p.date,'2026-10-17');
const orders=commitOrder(p,products,[],'Aanya','m1');assert.equal(orders[0].total,900);assert.equal(available(products[0],'2026-10-17',orders),3);
assert.throws(()=>commitOrder(p,products,orders,'Aanya','m1'),/already/);
assert.throws(()=>commitOrder({...p,quantity:4},products,orders,'New','m2'),/capacity/);
assert.throws(()=>commitOrder({...p,productId:'redvelvet'},products,[],'New','m3'),/capacity/);
assert.ok(inspect({...p,quantity:null},products,[]).errors.length);
assert.equal(sampleParse('1 kg chocolate cake price kya hai').quantity,null);
assert.equal(sampleParse('I need 2 boxes of cupcakes tomorrow').quantity,2);
assert.equal(recordPayment(orders[0],450).paid,450);assert.throws(()=>recordPayment(orders[0],901));assert.throws(()=>recordPayment(orders[0],-1));
assert.match(replyFor({...p,productId:'redvelvet'},products,[]),/available nahi hai/);
assert.equal(available(products[0],'2026-10-17',[{...orders[0],status:'cancelled'}]),4);
assert.equal(businessDate(new Date('2026-10-16T20:00:00Z')),'2026-10-17');
assert.equal(nextDate('2026-12-31'),'2027-01-01');
assert.equal(sampleParse('Kal 1 chocolate cake book karna hai','2026-10-17').date,'2026-10-18');
assert.throws(()=>commitOrder({...p,intent:'question'},products,[],'Aanya','new'),/Only an order/);
assert.equal(recordPayment(orders[0],0.29).paid,0.29);
assert.equal(recordPayment(recordPayment(orders[0],0.1),0.2).paid,0.3);
assert.ok(inspect({...p,date:'2026-02-30'},products,[]).errors.length);
console.log('Domain checks passed: reservations, capacity, duplicate protection, dates and payment precision.');
